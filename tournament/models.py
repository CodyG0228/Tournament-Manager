from django.db import models
from django.utils import timezone


#single event (i.e. "Friday Night Mario Kart").
#game_type stores a preset key from Bracket.py GAME_PRESETS (e.g. 'mario_kart').
class Tournament(models.Model):
    FORMAT_CHOICES = [
        ('single_elimination', 'Single Elimination'),
        ('double_elimination', 'Double Elimination'),
        ('swiss', 'Swiss'),
        ('free_for_all', 'Free-for-All'),
    ]

    name = models.CharField(max_length=200)
    game_type = models.CharField(max_length=100, default='unknown', help_text="e.g., 'pokemon_tcg', 'mario_kart'")
    date = models.DateField()
    status = models.CharField(max_length=50, default='SETUP')
    format = models.CharField(max_length=50, choices=FORMAT_CHOICES, default='single_elimination')
    num_rounds = models.PositiveIntegerField(default=3)
    max_players = models.PositiveIntegerField(default=16)

    def __str__(self):
        return self.name

class Player(models.Model):
    #display name, has to be unique
    username = models.CharField(max_length=100, unique=True)
    player_id = models.CharField(max_length=50, unique=True, blank=True) #ID generated by the system
    wins = models.IntegerField(default=0)
    losses = models.IntegerField(default=0)

    def __str__(self):
        return self.username

class TournamentRegistration(models.Model):
    #linking player to tournament, pair is unique
    tournament = models.ForeignKey(Tournament, on_delete=models.CASCADE, related_name='registrations')
    player = models.ForeignKey(Player, on_delete=models.CASCADE)
    registered_date = models.DateTimeField(default=timezone.now)
    is_active = models.BooleanField(default=True)
    checked_in = models.BooleanField(default=False) #only checked-in players go into matches

    class Meta:
        unique_together = ('tournament', 'player') #preventing double registration

    def __str__(self):
        return f"{self.player.username} registered for {self.tournament.name}"

class Match(models.Model):
    #one round within a tourney
    tourney = models.ForeignKey(Tournament, on_delete=models.CASCADE, related_name='matches')
    match_id = models.CharField(max_length=100, unique=True) #ID that is unique to the match itself
    round_number = models.IntegerField()
    is_bye = models.BooleanField(default=False)

    def __str__(self):
        return f"Match {self.match_id} in Round {self.round_number}"


class MatchParticipant(models.Model):
    #a players entry in a match
    match = models.ForeignKey(Match, on_delete=models.CASCADE, related_name='participants')
    player = models.ForeignKey(Player, on_delete=models.PROTECT) #can't delete player if they are currently in a match
    score = models.IntegerField(default=0)
    rank = models.IntegerField(null=True, blank=True)

    def __str__(self):
        return f"{self.player.username} participant in {self.match.match_id}"


#persisted bracket state written by Bracket.py BracketPageManager.save_bracket_state_to_db().
#only one row per tournament, the bracket_data holds the JSON payload the frontend receives
class TournamentBracket(models.Model):
    tournament = models.OneToOneField(Tournament, on_delete=models.CASCADE, related_name='bracket')
    current_round = models.IntegerField(default=1)
    bracket_data = models.JSONField(default=dict)

    def __str__(self):
        return f"Bracket for {self.tournament.name} (Round {self.current_round})"